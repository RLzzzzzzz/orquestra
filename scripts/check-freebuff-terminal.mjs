import fs from 'node:fs';
import path from 'node:path';
import headless from '@xterm/headless';
import { Workspace } from '../server/workspace.mjs';
import { Terminals } from '../server/terminals.mjs';
import { Orchestration } from '../server/orchestration.mjs';
const dir = fs.mkdtempSync(path.join(process.cwd(), '.local-freebuff-check-'));
const workspace = new Workspace(dir, dir);
const projectId = workspace.state.projects[0].id;
const source = workspace.addAgent({ projectId, provider: 'freebuff', name: 'Freebuff' });
const term = new headless.Terminal({ cols: 100, rows: 28, allowProposedApi: true });
const terminals = new Terminals(e => { if (e.type === 'output') term.write(e.data); });
const orchestration = new Orchestration(workspace, terminals, { summaries: () => [] }, 4317);
const agent = orchestration.start(projectId, source.id);
term.onData(data => terminals.write(agent.id, data));
await new Promise(resolve => setTimeout(resolve, 9000));
console.log(JSON.stringify(terminals.info(agent.id)));
console.log(Array.from({ length: term.buffer.active.length }, (_, i) => term.buffer.active.getLine(i)?.translateToString(true) || '').join('\n').trim());
terminals.dispose(); term.dispose();
setTimeout(() => process.exit(0), 1000);
