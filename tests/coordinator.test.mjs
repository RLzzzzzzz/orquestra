import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { Workspace } from '../server/workspace.mjs';
import { Orchestration } from '../server/orchestration.mjs';

test('selects and persists coordinator, isolates Freebuff config, blocks invalid switches', t => {
  const dir = fs.mkdtempSync(path.join(process.cwd(), '.local-coordinator-'));
  const originalPath = process.env.PATH;
  for (const name of ['codex', 'opencode', 'freebuff']) fs.writeFileSync(path.join(dir, name + (process.platform === 'win32' ? '.cmd' : '')), '');
  process.env.PATH = dir + path.delimiter + originalPath;
  t.after(() => { process.env.PATH = originalPath; fs.rmSync(dir, { recursive: true, force: true }); });
  const workspace = new Workspace(dir, dir), projectId = workspace.state.projects[0].id;
  const first = workspace.addAgent({ projectId, provider: 'codex', name: 'Codex' });
  const second = workspace.addAgent({ projectId, provider: 'opencode', name: 'OpenCode' });
  const freebuff = workspace.addAgent({ projectId, provider: 'freebuff', name: 'Freebuff' });
  let current = {}, launch, stopped = 0, active = [];
  const terminals = { info: () => current, start(agent, options) { launch = options; current = { mode: 'coordinator', status: 'running' }; }, stop() { stopped++; current = {}; } };
  const orchestration = new Orchestration(workspace, terminals, { summaries: () => active }, 4317);
  const coordinator = orchestration.start(projectId, first.id);
  const oldToken = launch.env.ORQUESTRA_MCP_TOKEN;
  orchestration.start(projectId, first.id); assert.equal(stopped, 0);
  orchestration.start(projectId, second.id);
  assert.equal(stopped, 1); assert.equal(coordinator.provider, 'opencode');
  assert.equal(coordinator.sourceAgentId, second.id); assert.equal(first.coordinator, undefined);
  assert.equal(orchestration.scope(oldToken), undefined);
  assert.ok(JSON.parse(launch.env.OPENCODE_CONFIG_CONTENT).mcp.orquestra);
  active = [{ status: 'running' }];
  assert.throws(() => orchestration.start(projectId, first.id), /tarefas ativas/);
  active = [];
  assert.throws(() => orchestration.start(projectId, 'foreign-id'), /deste projeto/);
  orchestration.start(projectId, freebuff.id);
  const config = fs.readFileSync(path.join(launch.launch.cwd, '.agents', 'mcp.json'), 'utf8');
  assert.ok(!config.includes(launch.env.ORQUESTRA_MCP_TOKEN));
  assert.ok(config.includes('$ORQUESTRA_MCP_TOKEN'));
  assert.equal(new Workspace(dir, dir).state.agents.find(a => a.coordinator).provider, 'freebuff');
  for (const provider of ['antigravity', 'hermes']) assert.equal(workspace.addAgent({ projectId, provider, name: provider }).provider, provider);
});
